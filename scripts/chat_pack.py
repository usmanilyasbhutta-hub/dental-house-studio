"""Chat pack: one page for a normal (non-code) Claude Project, so planning chats know the rules, clinic facts, video types
and the owner's taste without reading the repo. Built from the real files, so it never drifts.

  python3 scripts/chat_pack.py   # writes docs/chat-pack.md (also runs inside npm run map / npm run check)
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
read = lambda p: (ROOT / p).read_text()

# One line per brief type, for a planner who never sees the code. Checked against schema.ts below.
TYPES = {
    "offer": "promo/offer reel: hook, 2–4 points, price only if confirmed, CTA",
    "offer-reel": "10–12 s hook-first offer: before+after on frame 1, value before price, static price, WhatsApp CTA; format 9:16 or 4:5",
    "education": "doctor-led tips or myth-busting with numbered steps (needs a PubMed source for claims)",
    "case": "before/after clinical case (consent required, photos unwarped and uncropped)",
    "talking-head": "edit of a doctor speaking to camera: cut filler, word captions, callouts",
    "procedure": "3D step-by-step explainer of a treatment (implant, crown, filling…)",
    "photo-layout": "annotate / split / grid / loupe on clinical photos",
    "anatomy-map": "accurately traced anatomy zones on a clinical photo",
    "map-route": "illustrative 3D city route to the clinic",
    "blueprint": "technical drawing of a tooth or implant, drawn line by line",
    "receipt": "printed-receipt animation for a price list (prices must be confirmed with a date)",
    "sketch": "hand-drawn explainer, doodles drawn stroke by stroke; 14 media (pencil, watercolour, chalkboard, clay…)",
    "diagram": "timeline, roadmap, flowchart, cycle, layers, iceberg, tree, matrix or infographic",
}


def section(md, title):
    m = re.search(rf"^## {re.escape(title)}.*?\n(.*?)(?=^## |\Z)", md, re.S | re.M)
    return m.group(1).strip() if m else ""


def main():
    claude, taste, brand, schema = read("CLAUDE.md"), read("docs/taste.md"), read("src/brand.ts"), read("src/brief/schema.ts")
    types = re.findall(r'type: z\.literal\("([\w-]+)"\)', schema)
    missing = [t for t in types if t not in TYPES]
    if missing:
        raise SystemExit(f"chat_pack.py: add a line for new brief type(s) {missing}")
    clinic = re.search(r"export const clinic = \{(.*?)\} as const", brand, re.S).group(1)
    clinic = re.sub(r"\s*/\*\*.*?\*/", "", clinic).strip()
    clinic = "\n".join(l.strip() for l in clinic.splitlines() if l.strip())
    example = read("briefs/examples/blueprint-tooth.yaml").strip()
    out = f"""# Dental House: chat pack (generated by `scripts/chat_pack.py`; do not edit by hand)

For **planning chats** (a normal Claude Project, no code): ideas, scripts, hooks, captions, content calendar, briefs.
Videos are **made** in a Claude Code session on the `dental-house-studio` repo. Your output here is a **brief** (YAML,
format below) or a script the owner pastes into the Code session with "make this".

## Golden rules (never break)
{section(claude, "Golden rules (never break these)")}

## Clinic facts (only these; never invent websites, hours or prices: ask)
```
{clinic}
```

## Brand and specs
{section(claude, "Brand decisions (owner, Nov 2026)")}
{section(claude, "Brand (from the dental-house-brand-reel skill)")}
Video: 1080×1920 vertical, ≤ 90 s (house length 15–30 s, education ≤ 35 s). Keep text out of the top 220 px and bottom 380 px.
Something must change on screen by 1.5 s.

## Video types (brief `type:`)
""" + "\n".join(f"- `{t}`: {TYPES[t]}" for t in types) + f"""

## The owner's taste
{section(taste, "Who decides (authority order)")}

### Baseline, not a cage
{section(taste, "Baseline, not a cage (owner rule, 2026-11-16)")}

### Preferences
{section(taste, "Standing preferences")}

### Not wanted
{section(taste, "Not wanted")}

### Still open (ask when relevant, one at a time)
{section(taste, "Open questions (ask when the next video makes them relevant, one at a time)")}

## Working with the owner (a dentist, not an editor)
- Offer 2–3 directions in plain words: one **baseline**, one **stretch** (breaks one preference on purpose, say which and why).
- Ask at most two A/B questions. Never present a guess as the owner's preference.
- Any reaction ("like this", "too fast", picks B) matters: end your reply with a line
  `Taste note for Code session: <owner's exact words> → <what it means>` so it gets logged in `docs/taste.md`.

## Brief format (example; the Code session validates and fills the rest)
```yaml
{example}
```
Set `demo: false` for real videos. Claims need `sources` (PubMed). Real prices need `prices_confirmed_on`.
"""
    (ROOT / "docs/chat-pack.md").write_text(out)
    print(f"chat pack → docs/chat-pack.md (~{len(out) // 4:,} tokens)")


if __name__ == "__main__":
    main()
